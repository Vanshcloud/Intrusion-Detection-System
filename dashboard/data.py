import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:  # ids.* helpers (metrics, SHAP) live in src/
    sys.path.insert(0, str(ROOT / "src"))
GEN = ROOT / "reports" / "generated"
FIG = ROOT / "reports" / "figures" / "m5"
NA = "not available"
SHAP_TOL = 1e-9  # live vs stored SHAP agreement required by the case explorer
from ids.metrics import UNSTABLE_SUPPORT as SMALL_SUPPORT  # noqa: E402  (labels below this are case-level only)
FIGURES = {  # Milestone 5 figures reused as-is (generated by scripts/m5_analyze.py)
    "beeswarm": "beeswarm_uniform.png", "dependence": "dependence.png", "family_groups": "family_group_share.png",
    "stability": "stability_bootstrap_ranks.png", "model_comparison": "model_comparison_importance.png",
    "fp_features": "fp_features_by_daygroup.png", "fpr_direction": "fpr_by_direction_val_test.png",
    "score_tails": "benign_score_tails_val_test.png",
}
FAMILY_NAMES = {"lr": "Logistic Regression", "rf": "Random Forest", "lgbm": "LightGBM"}
PROTOCOL_NAMES = {"E1_primary": "chronological (primary)", "E2_random": "random split (comparison)"}


# ------------------------------------------------------------------ raw access
@lru_cache(maxsize=None)
def read_json(rel):
    return json.loads((ROOT / rel).read_text())


@lru_cache(maxsize=None)
def read_csv(name):
    """reports/generated/<name>.csv; round-trip float parsing so stored scores compare exactly (callers must not mutate)."""
    return pd.read_csv(GEN / f"{name}.csv", float_precision="round_trip")


def frozen():
    return read_json("configs/m4_frozen.json")


def protocol():
    return read_json("configs/experiment_protocol_v1.json")


def facts():
    return read_json("reports/generated/m5_facts.json")


def figure(key):
    """Path of a Milestone 5 figure, or None if the file is missing."""
    p = FIG / FIGURES[key]
    return p if p.exists() else None


# ------------------------------------------------------------------ frozen experiment
def budgets():
    """Pre-declared FPR budgets as strings, strictest first (the strictest is the primary operating point)."""
    return sorted(frozen()["experiments"][0]["thresholds"], key=float)


def primary_budget():
    return budgets()[0]


def tag(e):
    return f"{e['experiment']}__{e['family']}"


def experiment(tag_):
    return next(e for e in frozen()["experiments"] if tag(e) == tag_)


def selected():
    fz = frozen()
    return next(e for e in fz["experiments"] if e["run_id"] == fz["overall_selected"])


def summary_row(tag_, subset="full_test", budget=None):
    s = read_csv("m4_test_summary")
    b = float(budget or primary_budget())
    r = s[(s.experiment == tag_) & (s.subset == subset) & np.isclose(s.budget, b)]
    if len(r) != 1:
        raise KeyError(f"no unique summary row for {tag_}/{subset}/{b}")
    return r.iloc[0].to_dict()


def headline():
    """Selected model at the primary budget: frozen threshold, validation and test metrics."""
    e, b = selected(), primary_budget()
    t = summary_row(tag(e), "full_test", b)
    v = e["val_at_threshold"][b]
    return {"run_id": e["run_id"], "tag": tag(e), "family": FAMILY_NAMES[e["family"]], "params": e["params"],
            "best_iteration": e["best_iteration"], "budget": float(b), "threshold": e["thresholds"][b],
            "val_fpr": v["fpr"], "val_recall": v["recall"], "val_fp": v["fp"], "val_fn": v["fn"],
            **{k: t[k] for k in ("n", "attack", "benign", "tp", "fp", "tn", "fn", "precision", "recall", "f1",
                                 "fpr", "pr_auc", "roc_auc")}}


def dataset_overview():
    """Cleaned row count and chronological partition sizes (primary protocol)."""
    c = read_json("reports/generated/m3_cleaning.json")
    p = read_csv("m3_partition_counts")
    p = p[p.protocol == "chrono"].groupby("partition").n.sum()
    return {"dataset": protocol()["source"]["dataset"], "rows_raw": c["rows_in"], "rows_removed": c["rows_removed_non_finite"],
            "rows_clean": c["rows_out"], **{f"n_{k}": int(v) for k, v in p.items()}}


def model_comparison(budget=None):
    """Test metrics of every E1/E2 model at one budget (from the single frozen test evaluation)."""
    rows = []
    for e in frozen()["experiments"]:
        if e["experiment"] not in PROTOCOL_NAMES:
            continue
        r = summary_row(tag(e), "full_test", budget)
        rows.append({"protocol": PROTOCOL_NAMES[e["experiment"]], "model": FAMILY_NAMES[e["family"]],
                     "selected": e["run_id"] == frozen()["overall_selected"],
                     **{k: r[k] for k in ("precision", "recall", "f1", "pr_auc", "roc_auc", "fpr", "fp", "fn")},
                     "val_fpr": e["val_at_threshold"][budget or primary_budget()]["fpr"]})
    return pd.DataFrame(rows)


def confusion(tag_=None, subset="full_test", budget=None):
    r = summary_row(tag_ or tag(selected()), subset, budget)
    return pd.DataFrame([[int(r["tn"]), int(r["fp"])], [int(r["fn"]), int(r["tp"])]],
                        index=["true benign", "true attack"], columns=["predicted benign", "predicted attack"])


def family_recall(tag_=None, subset="full_test", budget=None):
    """Binary-detector recall per original attack label (not multiclass accuracy)."""
    L = read_csv("m4_test_per_label")
    b = float(budget or primary_budget())
    d = L[(L.experiment == (tag_ or tag(selected()))) & (L.subset == subset) & np.isclose(L.budget, b)
          & (L.level == "label_original") & (L.role == "attack")]
    out = d[["label", "n", "flagged", "missed_or_clear", "rate", "ci95_low", "ci95_high"]].rename(
        columns={"flagged": "detected", "missed_or_clear": "missed", "rate": "recall"})
    out["small_support"] = out.n < SMALL_SUPPORT
    out["detected_of_n"] = out.detected.astype(int).astype(str) + "/" + out.n.astype(int).astype(str) + " detected"
    return out.sort_values("n", ascending=False).reset_index(drop=True)


def benign_alerts(tag_=None, budget=None):
    """Alert rate on benign and '- Attempted' labels (all are benign under the protocol-v1 target)."""
    L = read_csv("m4_test_per_label")
    b = float(budget or primary_budget())
    d = L[(L.experiment == (tag_ or tag(selected()))) & (L.subset == "full_test") & np.isclose(L.budget, b)
          & (L.level == "label_original") & (L.role != "attack")]
    return d[["label", "n", "flagged", "rate", "ci95_low", "ci95_high", "unstable"]].sort_values("n", ascending=False)


def small_support_labels():
    fr = family_recall()
    return fr[fr.small_support].sort_values("n")


# ------------------------------------------------------------------ SHAP (Milestone 5)
def shap_global():
    """Global mean |SHAP| ranking (full test census), group shares, and model-agreement / stability summaries."""
    f = facts()
    gp = read_csv("m5_group_share_by_population").set_index("population")
    return {"importance": read_csv("m5_global_importance"), "groups": gp.loc["all_test"].drop("n").sort_values(ascending=False),
            "n_test": f["n_test"], "n_uniform": f["n_uniform"], "base_log_odds": f["base_log_odds"],
            "base_probability": f["base_probability"], "n_inputs": f["n_model_inputs"],
            "additivity_error": f["stored_additivity_max_abs_prob_error"],
            "rf": read_csv("m5_lgbm_vs_rf_summary").set_index("population"),
            "e1e2": read_csv("m5_e1_vs_e2_summary").set_index("population"),
            "boot_top10_min": f["boot1000_top10_overlap_min"], "boot_top1_always": f["boot1000_top1_always"],
            "interaction_share": f["interaction_offdiag_share"], "families": read_csv("m5_family_top_features"),
            "interaction_hub": _hub(read_csv("m5_interactions_top"))}


def _hub(inter):
    """Feature appearing most often among the strongest interaction pairs."""
    return pd.concat([inter.feature_a, inter.feature_b]).value_counts().index[0]


# ------------------------------------------------------------------ false positives (Milestone 5)
