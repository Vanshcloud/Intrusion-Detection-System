"""Dashboard data layer: every number shown by the dashboard comes from a function in this module.

Pure functions (no Streamlit) over committed, machine-readable artifacts: configs/*.json,
reports/generated/m3_*/m4_*/m5_*/m6_* and reports/figures/m5/*.png. The frozen model is optional and is loaded only
for the prediction demo, after its SHA-256 is checked against configs/m4_frozen.json. Nothing is trained, re-tuned,
re-thresholded or relabelled here.
"""
import json
import sys
from functools import lru_cache
from pathlib import Path

