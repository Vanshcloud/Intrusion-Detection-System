def demo_features():
    return [c[3:] for c in demo_cases().columns if c.startswith("f__")]


def case_contributions(row, k=8):
    """Top-k SHAP contributions (log-odds) toward attack and toward benign for one demo row."""
    s = pd.Series({c[3:]: row[c] for c in row.index if c.startswith("s__")}, dtype=float)
    val = {c[3:]: row[c] for c in row.index if c.startswith("f__")}
    df = pd.DataFrame({"feature": s.index, "shap": s.values, "value": [val[f] for f in s.index]})
    pos = df[df.shap > 0].sort_values("shap", ascending=False, kind="mergesort").head(k)
    neg = df[df.shap < 0].sort_values("shap", kind="mergesort").head(k)
    return pos.reset_index(drop=True), neg.reset_index(drop=True)


def reconstructed_score(row):
    """sigmoid(base + sum SHAP) from the stored SHAP values (base from Milestone 5 facts)."""
    z = facts()["base_log_odds"] + sum(row[c] for c in row.index if c.startswith("s__"))
    return float(1 / (1 + np.exp(-z)))


def model_export():
    """Record of the committed text export of the frozen model (configs/m6_model_export.json)."""
    return read_json("configs/m6_model_export.json")


def model_inputs():
    """Frozen model inputs relative to the manifest's default feature set (from the export record)."""
    inputs = model_export()["input_features"]
    default = read_json("configs/feature_manifest_v1.json")["feature_sets"]["default"]
    return {"n": len(inputs), "n_default": len(default), "has_protocol": "Protocol" in inputs,
            "dropped": [c for c in default if c not in inputs]}


def model_path():
    return ROOT / model_export()["export_path"]


def load_model(path=None, expected_sha=None):
    """Load the committed LightGBM text export of the frozen selected model.

    Accepted only if its SHA-256 matches configs/m6_model_export.json, that record points at the model hash in
    configs/m4_frozen.json, and the booster's input order matches the recorded list.
    Returns (booster or None, status message); never raises for a missing or mismatching file."""
    import hashlib
    rec = model_export()
    path = Path(path or model_path())
    expected_sha = expected_sha or rec["export_sha256"]
    if rec["source_model_sha256"] != selected()["model_sha256"]:
        return None, "model export record does not refer to the frozen model in configs/m4_frozen.json; not loaded"
    if not path.exists():
        return None, f"model export not found: {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}"
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected_sha:
        return None, "model export present but its SHA-256 does not match configs/m6_model_export.json; not loaded"
    try:
        import lightgbm as lgb
        booster = lgb.Booster(model_file=str(path))
    except Exception as exc:  # corrupt or incompatible file: report, do not crash the page
        return None, f"model export could not be loaded: {exc}"
    if booster.feature_name() != [c.replace(" ", "_") for c in rec["input_features"]]:
        return None, "model export input order differs from configs/m6_model_export.json; not loaded"
    return booster, ("text export of the frozen model loaded; SHA-256 matches configs/m6_model_export.json, which "
                     "records the original model hash from configs/m4_frozen.json")


def live_explain(booster, row):
    """Score one demo row with the frozen-model export and recompute its SHAP values; compare with stored values."""
    feats = model_export()["input_features"]
    x = np.array([[row[f"f__{f}"] for f in feats]], dtype=float)
    score = float(booster.predict(x)[0])
    contrib = booster.predict(x, pred_contrib=True)[0]
    stored = np.array([row[f"s__{f}"] for f in feats], dtype=float)
    return {"score": score, "score_equal_stored": score == float(row["score"]),
            "shap_max_abs_diff": float(np.abs(contrib[:-1] - stored).max()),
            "base_equal_stored": float(contrib[-1]) == facts()["base_log_odds"]}


def validate_case_index(i):
    """Row index of a demo case; raises ValueError for anything that is not a valid index."""
    c = demo_cases()
    n = 0 if c is None else len(c)
    if isinstance(i, bool) or not isinstance(i, (int, np.integer)) or not 0 <= i < n:
        raise ValueError(f"case index must be an integer in [0, {n - 1}]")
    return int(i)


