# ------------------------------------------------------------------ novel vectors
def novel_overview():
    ns = read_csv("m3_novel_summary")
    r = ns[(ns.protocol == "chrono") & (ns.variant == "primary") & (ns.feature_set == "default")].iloc[0].to_dict()
    rows = []
    for e in frozen()["experiments"]:
        if e["experiment"] != "E1_primary":
            continue
        for sub in ("full_test", "novel_test"):
            s = summary_row(tag(e), sub)
            rows.append({"model": FAMILY_NAMES[e["family"]], "subset": sub, "n": s["n"], "attack": s["attack"],
                         "benign": s["benign"], "recall": s["recall"], "fpr": s["fpr"], "precision": s["precision"],
                         "fp": s["fp"], "fn": s["fn"]})
    return r, pd.DataFrame(rows)


def novel_composition():
    """Attack rows per label in the full test set vs the novel-vector subset (chronological, default features)."""
    d = read_csv("m3_novel_by_label")
    d = d[(d.protocol == "chrono") & (d.variant == "primary") & (d.feature_set == "default") & (d.family != "BENIGN")]
    d = d[["label_original", "full", "novel", "exact_overlap_share"]].rename(columns={"label_original": "label"})
    d["share_of_attacks_full"] = d.full / d.full.sum()
    d["share_of_attacks_novel"] = d.novel / d.novel.sum()
    d["retained"] = d.novel / d.full
    return d.sort_values("full", ascending=False).reset_index(drop=True)


