def pct(x, d=2):
    return NA if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.{d}f} %"


def num(x, d=None):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return NA
    return f"{int(x):,}" if d is None else f"{x:.{d}f}"
