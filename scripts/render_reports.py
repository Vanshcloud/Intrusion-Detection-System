      f"| A. Chronological 70/30 within each (day, label) | test overlap {ov('A_chrono_within_label'):.3f} exact / {co('A_chrono_within_label'):.3f} non-timing vs random {ov('D_random_stratified'):.3f} / {co('D_random_stratified'):.3f}; moves test later in time; every label present in train | Usable as the base, **not sufficient alone** |\n"
      f"| A + test-side embargo 120 s / 600 s | attack test rows {n(a.loc[('A_chrono_embargo_120s', 'attacks'), 'n_test'])} / {n(a.loc[('A_chrono_embargo_600s', 'attacks'), 'n_test'])} of {n(a.loc[('A_chrono_within_label', 'attacks'), 'n_test'])}; overlap barely changes | Rejected: large test loss, little benefit |\n"
      f"| A + training-side purge | {n(D['purge']['train_rows_purged'])} training rows removed; no test loss; removes flow-interval overlap across the cut | **Adopt** |\n"
