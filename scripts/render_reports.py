# ======================================================================= LEAKAGE_AUDIT
def leakage_audit(D):
    ids, sfb, sfa, ss, spl, dup = D["ids"], D["sfb"], D["sfa"], D["ss"], D["spl"], D["dup"]
    b = sfb.set_index("feature")["bal_acc_binary"]
    piv = sfa.pivot(index="label", columns="feature", values="bal_acc")
    out = []
    w = out.append
    w("# Leakage Audit — improved CIC-IDS2017 (Milestone 2)\n")
    w("Generated by `scripts/render_reports.py` from `reports/generated/*`. Exploratory screening only; no model has been "
      "trained or evaluated. Each section separates **Observed evidence** from **Interpretation / possible risk**.\n")
    w("Screening method: for each column, a one-feature classifier fitted on a random half and scored (balanced accuracy, "
      "0.5 = chance) on the other half — a depth-3 decision tree for numeric columns, a value→majority-label lookup for "
      "identifier columns. Binary target: attack vs benign with Attempted → Benign. Per-attack: that label vs a fixed 50k "
      "sample of same-day benign flows. Mutual information on a 50k/50k stratified sample. Random halves make these "
      "scores optimistic by construction (duplicates), which is acceptable for *flagging*.\n")

    w("## 1. Feature classification\n")
    def bl(f):
        return f"{b[f]:.3f}" if f in b else "—"
    cls = [
        ("`Label`", "TARGET", "Primary target (binary / multiclass derived from it)."),
        ("`Attempted Category`", "TARGET", "Target-derived: set by the labelling logic, non-(−1) exactly on `- Attempted` labels. Used only to implement the label policy; never a feature."),
        ("`id`", "METADATA ONLY", f"Row number in file (1..n); stable record id together with `source_file`. Weakly predictive through file order (binary {bl('id')})."),
        ("`source_file`, `source_row`", "METADATA ONLY", "Provenance added by us; day determines which attacks exist."),
        ("`Timestamp` / `ts`", "METADATA ONLY", f"Needed for splitting. Alone it separates attacks from same-day benign (per-attack {piv['t'].min():.2f}–{piv['t'].max():.2f}) because each attack occupies one window. No time-of-day features."),
        ("`Flow ID`", "METADATA ONLY", f"Concatenation of IPs, ports, protocol; not unique (binary {bl('Flow ID')}). Not a valid grouping key (port reuse)."),
        ("`Src IP`", "EXCLUDED DUE TO LEAKAGE RISK", f"172.16.0.1 is the source of {pct(ids['attack_rows_from_172.16.0.1_share'])} of successful-attack rows but only {ids['labels_src_172.16.0.1'].get('BENIGN', 0)} benign rows; per-attack score 1.0 for every 172.16.0.1 attack. Kept as metadata for audits."),
        ("`Dst IP`", "EXCLUDED DUE TO LEAKAGE RISK", f"Best single binary separator of all columns ({bl('Dst IP')}); victims are fixed hosts (192.168.10.50/.51, 205.174.165.73)."),
        ("`Src Port`", "EXCLUDED DUE TO LEAKAGE RISK", f"Ephemeral; the authors' labelling rules use specific source ports (e.g. Heartbleed 45022: per-attack {piv.loc['Heartbleed', 'Src Port']:.2f})."),
        ("`Dst Port`", "REQUIRES EXPERIMENT", f"Service semantics are legitimate, but attacks target fixed ports (binary {bl('Dst Port')}; Heartbleed 444 and Botnet 8080 {piv.loc['Heartbleed', 'Dst Port']:.2f}/{piv.loc['Botnet', 'Dst Port']:.2f}). With/without ablation."),
        ("`Protocol`", "MODEL FEATURE", f"Four codes (0, 1, 6, 17); not separating on its own (binary {bl('Protocol')})."),
        ("`FWD Init Win Bytes`, `Bwd Init Win Bytes`, `Fwd Seg Size Min`", "REQUIRES EXPERIMENT", "Host/OS TCP configuration rather than behaviour (hypothesis); Bwd Init Win Bytes ≥0.99 for Hulk, DDoS, SSH-Patator. Ablation."),
        ("`Fwd Header Length`, `Bwd Header Length`", "REQUIRES EXPERIMENT", "Probable 16-bit overflow (DATA_AUDIT §6)."),
        ("Backward size features (`Total Length of Bwd Packet`, `Bwd Packet Length *`, `Subflow Bwd Bytes`, …)", "MODEL FEATURE (flagged)", "Top binary separators; encode the victim server's response sizes (DoS Hulk/DDoS share four exact values). Watch in SHAP."),
        ("All other CICFlowMeter statistics, `ICMP Code`, `ICMP Type`", "MODEL FEATURE", "Flow behaviour; constant columns handled inside the pipeline."),
    ]
    w(md(pd.DataFrame(cls, columns=["Column(s)", "Class", "Reason"])))

    w("\n## 2. Direct target leakage\n")
    w("**Observed evidence.** `Attempted Category` is non-(−1) on exactly the `- Attempted` labels "
      f"(consistency check: {D['lab']['attempted_flag_consistent_with_label_suffix']}). No other column is a copy of the label.\n")
    w("**Interpretation / risk.** Including `Attempted Category` would leak the label policy itself. Excluded by `model_features()` "
      "and asserted in `tests/test_basics.py` and `tests/test_dataset.py`.\n")

    w("## 3. Identifier leakage\n")
    w("**Observed evidence.**\n")
    w(md(D["idp"], 4))
    w("\nSingle-identifier balanced accuracy per attack (vs same-day benign):\n")
    w(md(piv[["Src IP", "Dst IP", "Src Port", "Dst Port", "Protocol", "t"]].reset_index(), 3))
    w("\n**Interpretation / risk.** The labels were *constructed* from IP, port and time rules (authors' labelling logic), "
      "so any of these columns lets a model reproduce the labelling rule rather than detect behaviour. Botnet and "
      "Infiltration sources are ordinary victim hosts that also generate benign traffic, so for those, `Src IP` is weak "
      "but `Dst IP`/`Dst Port` (the C2 server) are perfect. Excluding IPs does not remove host identity entirely: "
      "TCP-stack fields (§1) may re-encode it.\n")

    w("## 4. Temporal leakage\n")
    w("**Observed evidence.** Every attack label lives in one contiguous window on one day (DATA_AUDIT §5); files are not "
      "time-ordered; flows last up to 120 s, so a flow starting before a split point can overlap flows after it. Repeated "
      "identical vectors in scans recur within ≤ 1 s (DATA_AUDIT §7).\n")
    w("**Interpretation / risk.** A random split places each test flow next to near-identical training flows from the same "
      "second. Time itself is a near-perfect attack indicator within a day, so no time-derived feature may be used.\n")

    w("## 5. Duplicate leakage and split simulation\n")
    w("**Observed evidence.** Candidate 70/30 designs simulated on the full data (no model): share of test rows whose exact "
      "feature vector (or non-timing vector, or Flow ID) also occurs in training. Weighted over labels.\n")
    w(md(ss, 3))
    w(f"\nPurging (A_chrono_purged_train) removes {n(D['purge']['train_rows_purged'])} training rows "
      f"({n(D['purge']['attack_train_rows_purged'])} attack) whose flow interval reaches past the per-label cut; "
      "the embargo variants instead discard test rows that start within E s after the cut.\n")
